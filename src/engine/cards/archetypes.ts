const lp = (g: GameState, uid: string) => {
  const p = g.cards[uid].controller;
  return [g.players[p].lp, g.players[opp(p)].lp] as const;
};

const countField = (g: GameState, uid: string, pred: (defId: string, u: string) => boolean, excludeSelf = false) => {
  const p = g.cards[uid].controller;
  return fieldMonsters(g, p).filter((u) => (!excludeSelf || u !== uid) && g.cards[u].faceUp && pred(g.cards[u].defId, u)).length;
};

const gyCount = (g: GameState, uid: string, pred: (defId: string) => boolean) => {
  const p = g.cards[uid].controller;
  return g.players[p].gy.filter((u) => pred(g.cards[u].defId)).length;
};

